package com.dadcoach.domain.reflection;

/**
 * Types of reflection that a father can complete.
 *
 * <ul>
 *   <li>MISSION — reflection on a completed mission</li>
 *   <li>WEEKLY — weekly reflection (typically Sunday)</li>
 *   <li>PHASE — reflection on coaching phase transition</li>
 * </ul>
 */
public enum ReflectionType {
    MISSION,
    WEEKLY,
    PHASE
}
