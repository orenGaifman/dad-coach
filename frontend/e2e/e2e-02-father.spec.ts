test('progress and settings; deleting his data needs the typed word', async ({ page }) => {
  const yoav = seedYoav()
  await signIn(page, yoav.phone)
  await page.goto('/progress')
  await expect(page.getByRole('heading', { name: 'הישגים' })).toBeVisible()
  await expect(page.getByText('המפגש הראשון', { exact: true })).toBeVisible()
  await page.goto('/settings')
  await page.getByLabel('איך לקרוא לך').fill('יואב לוי')
  await page.getByRole('button', { name: 'שמירה' }).click()
  await expect(page.getByText('נשמר.')).toBeVisible()
  await page.getByRole('button', { name: 'מחיקת הנתונים שלי' }).click()
  const confirm = page.getByRole('button', { name: 'מחיקה לצמיתות' })
  await expect(confirm).toBeDisabled()
  await page.getByLabel(/כדי לאשר/).fill('מחיקה')
  await confirm.click()
  await expect(page).toHaveURL(/\/login$/)
  await expect(page.getByText('בקשת המחיקה התקבלה')).toBeVisible()
  expect(sql(`SELECT status FROM father WHERE id = ${yoav.id};`)).toBe('DELETED')
})
